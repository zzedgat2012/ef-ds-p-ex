/**
 * Generates resources/views/components/icon.blade.php from lucide-static.
 *
 * Run with `npm run icons` after adding a name to ICONS below.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'

const ICONS = [
  'arrow-left',
  'arrow-right',
  'calendar',
  'clock',
  'download',
  'external-link',
  'home',
  'mail',
  'menu',
  'search',
  'send',
  'x',
]

/**
 * Lucide removed its brand icons after v0.462.0, which is the version the
 * original React app pinned. Their markup is inlined here verbatim so the
 * rendered icons stay identical to the site being ported.
 */
const BRAND_ICONS = {
  github:
    '<path d="M15 22v-4a4.8 4.8 0 0 0-1-3.5c3 0 6-2 6-5.5.08-1.25-.27-2.48-1-3.5.28-1.15.28-2.35 0-3.5 0 0-1 0-3 1.5-2.64-.5-5.36-.5-8 0C6 2 5 2 5 2c-.3 1.15-.3 2.35 0 3.5A5.403 5.403 0 0 0 4 9c0 3.5 3 5.5 6 5.5-.39.49-.68 1.05-.85 1.65-.17.6-.22 1.23-.15 1.85v4" /><path d="M9 18c-4.51 2-5-2-7-2" />',
  linkedin:
    '<path d="M16 8a6 6 0 0 1 6 6v7h-4v-7a2 2 0 0 0-2-2 2 2 0 0 0-2 2v7h-4v-7a6 6 0 0 1 6-6z" /><rect width="4" height="12" x="2" y="9" /><circle cx="4" cy="4" r="2" />',
  facebook:
    '<path d="M18 2h-3a5 5 0 0 0-5 5v3H7v4h3v8h4v-8h3l1-4h-4V7a1 1 0 0 1 1-1h3z" />',
  instagram:
    '<rect width="20" height="20" x="2" y="2" rx="5" ry="5" /><path d="M16 11.37A4 4 0 1 1 12.63 8 4 4 0 0 1 16 11.37z" /><line x1="17.5" x2="17.51" y1="6.5" y2="6.5" />',
}

const inner = (svg) =>
  svg
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/<svg[\s\S]*?>/, '')
    .replace(/<\/svg>/, '')
    .split('\n')
    .map((line) => line.trim())
    .filter(Boolean)
    .join('')

const entries = {}

for (const name of ICONS) {
  const file = resolve('node_modules/lucide-static/icons', `${name}.svg`)
  entries[name] = inner(readFileSync(file, 'utf8'))
}

Object.assign(entries, BRAND_ICONS)

const body = Object.keys(entries)
  .sort()
  .map((name) => `        '${name}' => '${entries[name].replace(/'/g, "\\'")}',`)
  .join('\n')

const output = `{{--
    Lucide icons, mirroring the iconMap the React app used.

    Generated by \`npm run icons\` — edit scripts/generate-icons.mjs, not this file.

    Usage: <x-icon name="github" class="h-4 w-4" />
--}}

@props(['name'])

@php
    $icons = [
${body}
    ];
@endphp

@if (isset($icons[$name]))
    <svg {{ $attributes }} xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24"
        fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round"
        stroke-linejoin="round" aria-hidden="true">
        {!! $icons[$name] !!}
    </svg>
@endif
`

writeFileSync(resolve('resources/views/components/icon.blade.php'), output)

console.log(`Wrote ${Object.keys(entries).length} icons to resources/views/components/icon.blade.php`)
